def get_locale_from_request(request):
    """Определяет локаль из query (?lang=), session, cookie или Accept-Language."""
    # 1. Явный параметр запроса
    lang = request.args.get('lang') if request else None
    if lang and lang in SUPPORTED_LOCALES:
        return lang
    # 2. Из Flask session (устанавливается при смене языка)
    try:
        from flask import session
        lang = session.get('locale')
        if lang and lang in SUPPORTED_LOCALES:
            return lang
    except RuntimeError:
        pass  # вне контекста запроса
    # 3. Cookie
    if request and request.cookies.get('locale') in SUPPORTED_LOCALES:
        return request.cookies.get('locale')
    # 4. Accept-Language
    if request and request.accept_languages:
        best = request.accept_languages.best_match(SUPPORTED_LOCALES)
        if best:
            return best
    return DEFAULT_LOCALE


def get_translations(locale):
    """Возвращает словарь переводов для локали. Fallback на en."""
    if locale not in SUPPORTED_LOCALES:
        locale = DEFAULT_LOCALE
    return TRANSLATIONS.get(locale, TRANSLATIONS[DEFAULT_LOCALE]).copy()


def _(key, locale=None):
    """Возвращает перевод по ключу для текущей локали (из g.locale) или переданной."""
    if locale is not None:
        loc = locale
    else:
        try:
            from flask import g, has_app_context
            loc = getattr(g, 'locale', DEFAULT_LOCALE) if has_app_context() else DEFAULT_LOCALE
        except RuntimeError:
            loc = DEFAULT_LOCALE
    trans = get_translations(loc)
    return trans.get(key, key)
